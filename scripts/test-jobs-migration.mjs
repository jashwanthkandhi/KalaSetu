import { PGlite } from '../.test-tools/node_modules/@electric-sql/pglite/dist/index.js';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS; CREATE SCHEMA storage; CREATE TABLE storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint);');
await db.exec((await fs.readFile('supabase/schema.sql','utf8')).replace(/CREATE EXTENSION[^;]*;/,''));
await db.exec(await fs.readFile('supabase/product_expansion.sql','utf8'));
const sql = await fs.readFile('supabase/tier1_jobs.sql','utf8');
await db.exec(sql); await db.exec(sql);
let checks = 0;
function check(actual, expected) { assert.deepEqual(actual, expected); checks++; }
await db.exec('SET ROLE anon');
await assert.rejects(db.query('SELECT * FROM processing_jobs')); checks++;
await assert.rejects(db.query("SELECT * FROM kalasetu_claim_job('00000000-0000-0000-0000-000000000001')")); checks++;
await db.exec('RESET ROLE');
const id='00000000-0000-0000-0000-000000000002';
await db.query('INSERT INTO processing_jobs(id,owner_hash,request_hash,language,photo_path,audio_path,audio_suffix) VALUES($1,$2,$3,$4,$5,$6,$7)',[id,'a'.repeat(64),'hash','te','photo','audio','.wav']);
await db.exec('SET ROLE service_role');
const claim=()=>db.query("SELECT * FROM kalasetu_claim_job('00000000-0000-0000-0000-000000000003')");
check((await claim()).rows[0].attempts,1);
check((await claim()).rows.length,0);
await db.query("UPDATE processing_jobs SET lease_until=now()-interval '1 minute' WHERE id=$1",[id]);
check((await claim()).rows[0].attempts,2);
await db.query("UPDATE processing_jobs SET lease_until=now()-interval '1 minute',attempts=3 WHERE id=$1",[id]);
check((await claim()).rows.length,0);
check((await db.query('SELECT state FROM processing_jobs WHERE id=$1',[id])).rows[0].state,'FAILED');
await db.exec('RESET ROLE');
check((await db.query("SELECT public FROM storage.buckets WHERE id='processing-inputs'")).rows[0].public,false);
console.log(`${checks} durable job migration, private access, lease and recovery checks passed.`);
await db.close();
